        $roles = [
            'SUPER_ADMIN',
            'ADMIN',
            'DOKTER',
            'PERAWAT',
            'FARMASI',
            'LABORATORIUM',
            'KASIR',
        ];

        foreach ($roles as $role) {
            Role::firstOrCreate([
                'name' => $role,
                'guard_name' => 'web',
            ]);
        }
    }
}